-- Hospital Management System - Version 2
-- PostgreSQL Database Schema

--Run this script after connecting to the PostgreSQL database to create the necessary tables for the Hospital Management System.

CREATE TABLE IF NOT EXISTS patients (
    patient_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    age INTEGER NOT NULL CHECK (age >= 0 AND age <= 120),
    gender VARCHAR(20) NOT NULL,
    condition VARCHAR(255) NOT NULL
);